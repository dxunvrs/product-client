    private static final Map<Locale, Map<String, String>> DICTS = new HashMap<>();

    public Strings() {
        DICTS.put(RU, ruDict());
        DICTS.put(CS, csDict());
        DICTS.put(IT, itDict());
        DICTS.put(ES_DO, esDict());
    }

    public String get(Locale locale, String key) {
        Map<String, String> dict = DICTS.getOrDefault(locale, DICTS.get(RU));
        String value = dict.get(key);
        if (value == null) value = DICTS.get(RU).get(key);

        return value;
    }

    public String localeDisplayName(Locale l) {
        if (l.equals(RU)) return "Русский";
        if (l.equals(CS)) return "Čeština";
        if (l.equals(IT)) return "Italiano";
        if (l.equals(ES_DO)) return "Español (RD)";
        return l.toString();
    }

